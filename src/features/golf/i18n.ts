const DICT: Record<LanguageCode, Dict> = { ko, en, ja: {}, zh: {} };

function format(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** 언어별 t() 생성기 — ja/zh는 en으로, 그래도 없으면 ko, 최후엔 key 반환 */
export function makeT(lang: LanguageCode) {
  return (key: string, vars?: Record<string, string | number>): string => {
    const val = DICT[lang]?.[key] ?? DICT.en[key] ?? DICT.ko[key] ?? key;
    return format(val, vars);
  };
}

export type TFunc = ReturnType<typeof makeT>;
